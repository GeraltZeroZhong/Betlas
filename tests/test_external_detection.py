def test_foldseek_command_preserves_paths_and_passthrough(tmp_path):
    stub = tmp_path / "foldseek stub.py"
    stub.write_text(
        "import json,sys\nfrom pathlib import Path\n"
        "assert sys.argv[1] == 'easy-search'\n"
        "Path('arguments.json').write_text(json.dumps(sys.argv[1:]))\n"
        f"Path(sys.argv[4]).write_text({_hit()!r})\n"
    )
    query = tmp_path / "query input"
    target = tmp_path / "target db"
    query.touch()
    target.touch()
    work = tmp_path / "work"
    results = foldseek.run_baseline(
        query, target, command_prefix=[sys.executable, str(stub)],
        query_ids=["toy"], work_dir=work, extra_args=["--threads", "2"],
    )
    args = json.loads((work / "arguments.json").read_text())
    assert args[1:3] == [str(query), str(target)]
    assert args[-2:] == ["--threads", "2"]
    assert results[0].result == "BARREL"


def test_isitabarrel_score_boundary_and_missing_column(tmp_path):
    result_file = tmp_path / "results.tsv"
    result_file.write_text("MAP_NAME\tCC2_TO_H4\ntoy-positive\t0.25\ntoy-zero\t0\ntoy-negative\t-1\n")
    results = isitabarrel.load_results_tsv(result_file)
