def _hit(query="toy", target="reference", *, qcov=0.8, tcov=0.8, score=0.7):
    return f"{query}\t{target}\t10\t10\t8\t{qcov}\t{tcov}\t{score}\t{score}\t{score}\t0.01\t12\n"


def _toy_pdb(path):
    # Three invented residues on a line; the only contact within 4 A is ALA--GLY.
    lines = []
    for index, (residue, x) in enumerate(zip(["ALA", "GLY", "VAL"], [0, 3, 9], strict=True), 1):
        lines.append(
            f"ATOM  {index:5d}  CA  {residue} B{index:4d}    "
            f"{x:8.3f}{0:8.3f}{0:8.3f}{1:6.2f}{0:6.2f}           C\n"
        )
    path.write_text("".join(lines) + "TER\nEND\n")
    return path


def test_structure_converters_preserve_synthetic_chain_and_residues(tmp_path):
    structure = _toy_pdb(tmp_path / "toy.pdb")
    fasta = generate_structure_fasta(structure, tmp_path / "sequence", min_residues=1)
    assert Path(fasta.fasta_path).read_text() == ">toy_B\nAGV\n"
    with Path(fasta.residue_mapping_path).open() as handle:
        assert [row["residue_number"] for row in csv.DictReader(handle)] == ["1", "2", "3"]

    chains = generate_structure_chains(structure, tmp_path / "chains", min_residues=1)
    assert chains.records[0].chain_id == "B"
    assert foldseek_query_aliases(chains.records)["toy_B.pdb_A"] == "toy_B"
    atoms = [line for line in Path(chains.records[0].chain_path).read_text().splitlines()
             if line.startswith("ATOM")]
    assert [line[21] for line in atoms] == ["A", "A", "A"]

    maps = generate_structure_contact_maps(
        structure, tmp_path / "contacts", cutoff=4, local_exclusion=0, min_residues=1
    )
    # Only read the pickle just generated by the converter from invented coordinates.
    with Path(maps.records[0].map_path).open("rb") as handle:
        matrix = pickle.load(handle)
    np.testing.assert_array_equal(matrix, [[0, 1, 0], [1, 0, 0], [0, 0, 0]])
    assert matrix.dtype == np.float32
    assert maps.records[0].n_contacts == 1


def test_foldseek_coverage_exclusions_aliases_and_no_hit_rows(tmp_path):
    hits_file = tmp_path / "hits.tsv"
    hits_file.write_text(
        _hit("toy.pdb_A", "self.pdb_A", score=1)
        + _hit("toy.pdb_A", "short", qcov=0.1, score=0.99)
        + _hit("toy.pdb_A", "eligible", score=0.5)
    )
    rows = foldseek.summarize_hits(
        foldseek.load_hits_tsv(hits_file), query_ids=["toy", "absent"],
        query_aliases={"toy.pdb_A": "toy"}, target_aliases={"self.pdb_A": "self"},
        ignore_target_ids_by_query={"toy": {"self"}},
    )
    assert rows[0].result == "BARREL"
    assert rows[0].best_target == "eligible"
    assert rows[0].score == 0.5
    assert rows[0].hit_count == 2
    assert rows[0].eligible_hit_count == 1
    assert rows[0].ignored_target_hit_count == 1
    assert rows[1].result == "NON_BARREL" and rows[1].hit_count == 0


